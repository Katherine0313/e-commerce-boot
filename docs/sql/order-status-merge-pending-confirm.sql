-- ============================================================================
-- 合并订单状态「待确认收款(2)」到「待发货(3)」
--
-- 背景：code=2 是原 Node 后端真实支付场景下的「商家人工确认到账」（微信/支付宝异步回调
--       延迟、人工转账对账）。本项目支付是 mock 的，点一下直接成功，不存在到账延迟，
--       这一环纯属人工卡点——本地库曾积压 65 单卡在 2，商家不去逐单点「确认通过」，
--       订单永远进不了发货。故退役该状态，支付成功直接进入「待发货」。
--
-- code 位保留不动（不动 4/5/6，报表 SQL order_status <> 6 不受影响）：
--       1待付款 / 3待发货 / 4已发货 / 5已完成 / 6已取消
--       2 号空出来不再使用，OrderStatusEnum 里也没有对应枚举了。
--
-- 执行范围：本地库 + 生产库执行同一份 SQL（改本地必须同步生产）。
-- ============================================================================

-- ① 存量订单迁移：待确认(2) → 待发货(3)
--    （本脚本当时顺手回填了 confirm_at；该列随后已随「取消商家确认环节」一并删除，
--     见 docs/sql/drop-confirm-at.sql。回填语句留在这里仅作历史记录，不再有实际作用。）
--    不写 updated_at：MySQL 服务器时区是 UTC，NOW() 比 JVM 写的 LocalDateTime.now() 早 8 小时，
--    混用会让按时间筛选错乱（其余时间戳一律由 Java 传参）。
UPDATE `orders`
SET `order_status` = 3
WHERE `order_status` = 2;

-- ② 字段注释同步（去掉已退役的「2待确认」）
ALTER TABLE `orders`
    MODIFY COLUMN `order_status` tinyint NOT NULL DEFAULT '1'
    COMMENT '订单状态：1待付款 3待发货 4已发货 5已完成 6已取消';
