SELECT p.id, p.name, t.old_sales AS 旧售价, t.new_sales AS 新售价,
       ROUND(t.new_sales * 1.10, 2) AS 新划线价, ROUND(t.new_sales * 0.72, 2) AS 新成本价
FROM products p JOIN tmp_price_fix t ON p.name = t.product_name AND p.sales_price = t.old_sales
