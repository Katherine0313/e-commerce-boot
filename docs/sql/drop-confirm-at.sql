-- 删除 orders.confirm_at（2026-11-04）
--
-- 背景：confirm_at 原本记录「商家确认收款时间」，对应订单状态 2=待确认收款。
--       该状态已退役（客户付款直接进 3待发货），这列失去原始语义；
--       合并状态时曾临时复用它表示「进入待发货的时间」（与 pay_at 同值），
--       现在直接删掉，不留「确认环节」的残影。
--
-- 影响面：订单状态流转只记 pay_at / ship_at / finish_at；
--          后台按时间筛选的白名单去掉 confirm_at（pay_at 已在白名单内）。
--
-- 执行范围：本地库 + 生产库执行同一份 SQL（改本地必须同步生产）。
-- ============================================================================

ALTER TABLE `orders` DROP COLUMN `confirm_at`;
