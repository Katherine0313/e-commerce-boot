--   2. 商品若已被人工调过价（旧价对不上），本脚本会自动跳过，不会覆盖别人的修改；
--   3. 天然幂等 —— 第二次执行时旧价已不存在，匹配不到任何行，不会重复改价。
--
-- 影响面：只改 products 的三个价格字段，不动库存/销量/图片/详情；
--         历史订单价格记录在 order_items.price（快照），不受影响；
--         promotion / promotion_rule 等促销表当前为空，改价不触发促销错乱。
--
-- 回滚：从备份恢复 products 表，或用备份里的旧价反向更新。
-- ============================================================================

