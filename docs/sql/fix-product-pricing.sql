-- 3) 核对映射表条数应为 98（临时表只在当前连接有效）
SELECT COUNT(*) AS 映射条数 FROM tmp_price_fix;

-- 4) 确认将要被改动的行数与映射条数一致（不一致说明有商品被人工改过价，先排查）
SELECT COUNT(*) AS 待改行数
FROM products p JOIN tmp_price_fix t ON p.name = t.product_name AND p.sales_price = t.old_sales;

-- 5) 执行改价：售价写新价，划线价 = 售价 × 1.10，成本价 = 售价 × 0.72
UPDATE products p
JOIN tmp_price_fix t
  ON p.name = t.product_name AND p.sales_price = t.old_sales
SET p.sales_price  = t.new_sales,
    p.market_price = ROUND(t.new_sales * 1.10, 2),
    p.cost_price   = ROUND(t.new_sales * 0.72, 2);

-- 6) 统一全部商品的价格口径（未调价的 38 个商品也一起处理）
--    旧数据里 cost_price / market_price 同样是编的，出现了「成本价 > 售价」的倒挂
--    （如 iPhone 15 Pro 成本 9699 > 售价 8499），这里统一成 成本=售价×0.72、划线价=售价×1.10
UPDATE products
SET cost_price   = ROUND(sales_price * 0.72, 2),
    market_price = ROUND(sales_price * 1.10, 2)
WHERE cost_price IS NULL
   OR market_price IS NULL
   OR cost_price >= sales_price
   OR market_price <= sales_price
   OR cost_price <> ROUND(sales_price * 0.72, 2)
   OR market_price <> ROUND(sales_price * 1.10, 2);

-- 7) 改价后校验
-- 7.1 不应再有匹配到旧价的行（说明已全部改完）
SELECT COUNT(*) AS 仍为旧价行数
FROM products p JOIN tmp_price_fix t ON p.name = t.product_name AND p.sales_price = t.old_sales;

-- 7.2 价格关系自检：必须满足 成本价 < 售价 < 划线价（期望 0 行）
SELECT id, name, cost_price, sales_price, market_price
FROM products
WHERE cost_price >= sales_price OR (market_price IS NOT NULL AND market_price <= sales_price);

-- 7.3 各分类价格区间（改价后的分布）
SELECT c.name AS 分类, COUNT(*) AS 商品数,
       MIN(p.sales_price) AS 最低价, MAX(p.sales_price) AS 最高价,
       ROUND(AVG(p.sales_price), 2) AS 平均价
FROM products p JOIN categories c ON c.id = p.category_id
WHERE p.listing_status = 1
GROUP BY c.id, c.name
ORDER BY MIN(p.sales_price);

